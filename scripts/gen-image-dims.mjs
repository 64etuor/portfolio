// Regenerates src/components/projects/imageDims.ts — intrinsic width/height of every
// screenshot under public/projects, so next/image can reserve space (no CLS) and pick
// responsive AVIF/WebP variants. Run after adding/replacing screenshots:
//   npm run gen:image-dims
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const root = path.resolve('public')
const dir = path.join(root, 'projects')
const out = {}
for (const slug of fs.readdirSync(dir).sort()) {
  const sub = path.join(dir, slug)
  if (!fs.statSync(sub).isDirectory()) continue
  for (const file of fs.readdirSync(sub).sort()) {
    if (!/\.(png|jpe?g|webp|avif)$/i.test(file)) continue
    try {
      const { width, height } = await sharp(path.join(sub, file)).metadata()
      out[`/projects/${slug}/${file}`] = [width, height]
    } catch (e) {
      // Undecodable (e.g. zero-filled) files are left out — Gallery skips them
      // instead of rendering a broken image.
      console.warn(`skip ${slug}/${file}: ${e.message}`)
    }
  }
}
const body = Object.entries(out)
  .map(([k, [w, h]]) => `  '${k}': [${w}, ${h}],`)
  .join('\n')
fs.writeFileSync(
  path.resolve('src/components/projects/imageDims.ts'),
  `// GENERATED by scripts/gen-image-dims.mjs — do not edit by hand.\n// Intrinsic [width, height] of public/projects screenshots (for next/image).\nexport const IMAGE_DIMS: Record<string, readonly [number, number]> = {\n${body}\n}\n`,
)
console.log(`wrote ${Object.keys(out).length} entries`)
