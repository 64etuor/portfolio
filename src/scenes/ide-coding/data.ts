export const SRC = [
  'import { useEffect, useRef, useState } from "react";',
  'import { openStream } from "../lib/stream";',
  'import type { Sample, Anomaly } from "../lib/schema";',
  '',
  'const WINDOW = 32;',
  'const SIGMA = 3.0;',
  '',
  '// Real-time anomaly guard using a rolling standard deviation',
  'export function useAnomalyGuard(channel: string) {',
  '  const [anomalies, setAnomalies] = useState<Anomaly[]>([]);',
  '  const buffer = useRef<number[]>([]);',
  '',
  '  useEffect(() => {',
  '    const stream = openStream(channel);',
  '',
  '    stream.on("sample", (s: Sample) => {',
  '      const buf = buffer.current;',
  '      buf.push(s.value);',
  '      if (buf.length > WINDOW) buf.shift();',
  '',
  '      const mean = buf.reduce((a, b) => a + b, 0) / buf.length;',
  '      const dev = buf.reduce((a, b) => a + (b - mean) ** 2, 0) / buf.length;',
  '      const sigma = Math.sqrt(dev);',
  '',
  '      if (Math.abs(s.value - mean) > SIGMA * sigma) {',
  '        const hit = { ts: s.ts, value: s.value, mean };',
  '        setAnomalies((prev) => [...prev, hit]);',
  '      }',
  '    });',
  '',
  '    return () => stream.close();',
  '  }, [channel]);',
  '',
  '  return anomalies;',
  '}',
] as const

